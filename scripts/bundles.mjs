/**
 * Registers every graph bundle, once, from what is actually on disk.
 *
 *   pnpm bundles:build            # regenerate the manifest
 *   pnpm bundles:build --check    # fail if it is stale
 *
 * Why this exists: adding a journey used to mean editing three lists that did
 * not know about each other. `data/index.ts` imported and arrayed the bundles,
 * `cli/quotes.ts` kept its own `ALL`, and meanwhile `scripts/verify-live.mjs`
 * and `apps/web/scripts/check-bundle.mjs` globbed the directory. So a new
 * bundle file got HTTP verified against a server that had never loaded it, and
 * audited by nothing. Four sources of truth, three of them wrong the moment
 * anyone adds a file, and all four silently agreeing while the graph is short a
 * journey.
 *
 * A runtime glob would be the obvious fix and it is not available: Next and
 * Expo need static `import` specifiers to bundle JSON at all. So the imports
 * stay static and get generated, which is the same shape as `pnpm domains:build`
 * and has the same `--check` so CI notices a stale file.
 *
 * Dropping a `.json` into packages/core/src/data/graph/ and running this is now
 * the whole procedure for adding a journey.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const at = (p) => fileURLToPath(new URL(p, root));
const dir = "packages/core/src/data/graph/";

/**
 * Jurisdictions are a bare array of rows, not a bundle. It lives in the same
 * folder because it is seed data, and it is imported by name in index.ts.
 */
const SKIP = new Set(["jurisdictions.json", "manifest.ts"]);

const camel = (name) => name.replace(/[-_](.)/g, (_, c) => c.toUpperCase());

const files = readdirSync(at(dir))
  .filter((f) => f.endsWith(".json") && !SKIP.has(f))
  .sort();

const bundles = files.map((file) => {
  const name = file.replace(/\.json$/, "");
  const json = JSON.parse(readFileSync(at(dir + file), "utf8"));
  return {
    name,
    ident: camel(name),
    // A bundle carrying `*` templates is not a journey: nothing compiles it as
    // a goal, and there is no docs/research file behind it to audit quotes
    // against. The generator can see the difference, so nobody has to remember.
    isTemplate: Array.isArray(json.edgeTemplates) && json.edgeTemplates.length > 0,
    nodes: (json.nodes ?? []).length,
  };
});

// Journeys first, template bundles last. Load order decides which duplicate
// question definition wins in `dedupeQuestions`, so it is deliberate and stable
// rather than whatever readdir felt like today.
const ordered = [...bundles.filter((b) => !b.isTemplate), ...bundles.filter((b) => b.isTemplate)];

const rendered = `// Generated by scripts/bundles.mjs. Do not edit by hand.
// Add a bundle by dropping its .json in this folder and running: pnpm bundles:build
${ordered.map((b) => `import ${b.ident} from "./${b.name}.json";`).join("\n")}

/** Every bundle file in this folder, journeys first, templates last. */
export const seedBundleModules: unknown[] = [${ordered.map((b) => b.ident).join(", ")}];

/** Same order, as ids. */
export const seedBundleNames = [${ordered.map((b) => JSON.stringify(b.name)).join(", ")}] as const;

/**
 * The ones with a docs/research file behind them, so \`quotes:audit\` knows what
 * to audit without keeping its own copy of the list.
 */
export const journeyBundleNames = [${ordered
  .filter((b) => !b.isTemplate)
  .map((b) => JSON.stringify(b.name))
  .join(", ")}] as const;
`;

const target = at(dir + "manifest.ts");
const args = process.argv.slice(2);

if (args.includes("--check")) {
  let current;
  try {
    current = readFileSync(target, "utf8");
  } catch {
    current = null;
  }
  if (current !== rendered) {
    console.error("  data/graph/manifest.ts is stale, run: pnpm bundles:build");
    process.exit(1);
  }
  console.log(`${ordered.length} bundles registered, manifest current`);
  process.exit(0);
}

writeFileSync(target, rendered);
console.log(`packages/core/src/data/graph/manifest.ts written`);
for (const b of ordered) console.log(`  ${b.name.padEnd(20)} ${String(b.nodes).padStart(4)} nodes${b.isTemplate ? "  (templates)" : ""}`);
